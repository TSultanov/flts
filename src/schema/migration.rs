//! Explicit forward upgrades. Published converters must remain deterministic and immutable.
//!
//! Keep old `#[entity]` and versioned `#[container]` declarations in separate modules.
//! Register each adjacent change with [`Migration::map`], [`Migration::drop`] and
//! [`Migration::add`], then open the latest store through [`Migrations::migrate`].
//!
//! Nothing on disk is rewritten. A shard stays in the schema version its writer wrote
//! it in; opening through the registry reads every older shard, converts its revisions
//! in memory and adopts them into the latest store, preserving identity and ancestry.
//! A peer still on an older version keeps writing older shards, so call
//! [`Migrations::refresh`] wherever the latest store would call `refresh_peers`.
//!
//! Each converter must produce the same value on every replica; Rust cannot enforce
//! purity. Changing a released converter can make shared revision dots disagree.
//! Cross-row transformations, entity splits and downgrades are not supported.

use std::any::{Any, TypeId};
use std::collections::BTreeMap;
use std::marker::PhantomData;

use super::{
    Batch, Entity, Holds, Layout, MergeReport, Parent, Row, SchemaMetadata, ShardMark, Store,
    Table, Version,
};
use crate::{Error, Id, Result};

/// Raw revision access generated by `#[entity]`, without resolving concurrent values.
pub trait MigrationTable: Table {
    fn revision_value(&self, row: Row) -> Result<<Self::Of as Entity>::Value>;

    /// Appends a complete revision. The caller must audit the completed destination store.
    fn append_revision_value(
        &mut self,
        id: Id<Self::Of>,
        version: Version,
        parents: Vec<Parent>,
        value: <Self::Of as Entity>::Value,
    ) -> Result<()>;
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MigrationStepReport {
    pub from: u64,
    pub to: u64,
    pub converted_revisions: usize,
    pub dropped_revisions: usize,
}

#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct MigrationReport {
    pub steps: Vec<MigrationStepReport>,
}

type Convert<F, T> = dyn Fn(&F, &mut T) -> Result<(usize, usize)>;
struct Operation<F, T> {
    source: Option<&'static str>,
    destination: Option<&'static str>,
    convert: Box<Convert<F, T>>,
}

/// One adjacent version change. Every source and destination table must be declared once.
pub struct Migration<From, To> {
    operations: Vec<Operation<From, To>>,
}

impl<F: Store + 'static, T: Store + 'static> Default for Migration<F, T> {
    fn default() -> Self {
        Self::new()
    }
}

impl<F: Store + 'static, T: Store + 'static> Migration<F, T> {
    pub fn new() -> Self {
        Self {
            operations: Vec::new(),
        }
    }

    /// Converts all historical values, preserving IDs, dots, ancestry and persisted flags.
    /// The function must depend only on its input, never time, randomness or external state.
    /// Released converters must remain immutable so independently upgraded replicas agree.
    pub fn map<A: Entity, B: Entity>(mut self, convert: fn(A::Value) -> Result<B::Value>) -> Self
    where
        F: Holds<A>,
        T: Holds<B>,
        A::Table: MigrationTable,
        B::Table: MigrationTable,
    {
        self.operations.push(Operation {
            source: Some(A::NAME),
            destination: Some(B::NAME),
            convert: Box::new(move |from, to| {
                let source = <F as Holds<A>>::table(from);
                let target = <T as Holds<B>>::table_mut(to);
                let rows = Table::rows(source);
                for index in 0..rows {
                    let row = Row::trusted(index);
                    let value = convert(source.revision_value(row)?)?;
                    target.append_revision_value(
                        source.id_at(row)?.cast(),
                        source.versions().raw_at(row)?,
                        source.versions().parents(row)?.to_vec(),
                        value,
                    )?;
                }
                Ok((rows, 0))
            }),
        });
        self
    }

    /// Deliberately removes a table and every revision it contains.
    pub fn drop<A: Entity>(mut self) -> Self
    where
        F: Holds<A>,
    {
        self.operations.push(Operation {
            source: Some(A::NAME),
            destination: None,
            convert: Box::new(|from, _| Ok((0, Table::rows(<F as Holds<A>>::table(from))))),
        });
        self
    }

    /// Adds an empty table. Seeding new entities is a subsequent application write.
    pub fn add<B: Entity>(mut self) -> Self
    where
        T: Holds<B>,
    {
        self.operations.push(Operation {
            source: None,
            destination: Some(B::NAME),
            convert: Box::new(|_, _| Ok((0, 0))),
        });
        self
    }
}

type ErasedStore = Box<dyn Any>;
type Apply = dyn Fn(ErasedStore) -> Result<(ErasedStore, MigrationStepReport)>;
type Load = fn(&Layout, &[ShardMark]) -> Result<Option<(ErasedStore, Vec<ShardMark>)>>;
struct Step {
    from: SchemaMetadata,
    to: SchemaMetadata,
    from_type: TypeId,
    to_type: TypeId,
    sources: Vec<&'static str>,
    destinations: Vec<&'static str>,
    wanted_sources: Vec<&'static str>,
    wanted_destinations: Vec<&'static str>,
    load: Load,
    apply: Box<Apply>,
}

fn coverage(mut declared: Vec<&str>, mut wanted: Vec<&str>) -> Result<()> {
    declared.sort_unstable();
    wanted.sort_unstable();
    if declared != wanted || wanted.windows(2).any(|pair| pair[0] == pair[1]) {
        return Err(Error::invalid(format!(
            "migration must declare every table exactly once: expected {wanted:?}, found {declared:?}"
        )));
    }
    Ok(())
}

/// A linear registry ending at `Latest`. Registration is checked before any converter runs.
///
/// Declare schemas with `#[dbsync::container(schema = "library", version = 1)]`,
/// keeping historical declarations in versioned Rust modules. Register adjacent changes
/// with [`Migration`] and explicitly call [`Self::migrate`] before opening the latest store.
/// Normal opening and merging never migrate files; peers must reach the same schema first.
///
/// The complete chain is prepared in memory and published as one atomic replacement.
/// Cross-row transformations, entity splits, downgrades and unversioned files are unsupported.
pub struct Migrations<Latest> {
    steps: Vec<Step>,
    latest: PhantomData<fn() -> Latest>,
}

impl<L: Store + 'static> Default for Migrations<L> {
    fn default() -> Self {
        Self::new()
    }
}

impl<L: Store + 'static> Migrations<L> {
    pub fn new() -> Self {
        Self {
            steps: Vec::new(),
            latest: PhantomData,
        }
    }

    /// Registers a step; registration order does not matter. All registered steps must
    /// form an unambiguous chain ending at `Latest`, using the same Rust type at each join.
    pub fn step<F: Store + 'static, T: Store + 'static>(
        mut self,
        migration: Migration<F, T>,
    ) -> Self {
        let from = F::default();
        let to = T::default();
        self.steps.push(Step {
            from: from.schema_metadata(),
            to: to.schema_metadata(),
            from_type: TypeId::of::<F>(),
            to_type: TypeId::of::<T>(),
            sources: migration
                .operations
                .iter()
                .filter_map(|op| op.source)
                .collect(),
            destinations: migration
                .operations
                .iter()
                .filter_map(|op| op.destination)
                .collect(),
            wanted_sources: from.tables().iter().map(|t| t.entity()).collect(),
            wanted_destinations: to.tables().iter().map(|t| t.entity()).collect(),
            load: |layout, held| {
                let mut source = F::default();
                source.state_mut().detached_at(layout.clone(), held);
                let mut report = MergeReport::default();
                if source.collect(|_| true, &mut report)?.is_empty() {
                    return Ok(None);
                }
                source.state_mut().detached_at(layout.clone(), &[]);
                let all = source.collect(|_| true, &mut report)?;
                let marks = all.iter().filter_map(|batch| batch.mark).collect();
                source.adopt(all, &mut report)?;
                source.audit()?;
                Ok(Some((Box::new(source), marks)))
            },
            apply: Box::new(move |source| {
                let source = source
                    .downcast::<F>()
                    .map_err(|_| Error::invalid("migration source type mismatch"))?;
                let mut target = T::default();
                let mut report = MigrationStepReport {
                    from: F::SCHEMA_VERSION,
                    to: T::SCHEMA_VERSION,
                    converted_revisions: 0,
                    dropped_revisions: 0,
                };
                for operation in &migration.operations {
                    let (converted, dropped) = (operation.convert)(&source, &mut target)?;
                    report.converted_revisions += converted;
                    report.dropped_revisions += dropped;
                }
                target.absorb(source.clock())?;
                target.check_published()?;
                target.audit()?;
                target.refresh()?;
                Ok((Box::new(target), report))
            }),
        });
        self
    }

    fn registry(&self, latest: &SchemaMetadata) -> Result<BTreeMap<u64, &Step>> {
        latest.validate()?;
        let mut steps = BTreeMap::new();
        for step in &self.steps {
            step.from.validate()?;
            step.to.validate()?;
            if step.from.name != latest.name
                || step.to.name != latest.name
                || step.from.version.checked_add(1) != Some(step.to.version)
                || step.to.version > latest.version
            {
                return Err(Error::invalid(
                    "migrations must be adjacent forward steps in the latest schema family",
                ));
            }
            coverage(step.sources.clone(), step.wanted_sources.clone())?;
            coverage(step.destinations.clone(), step.wanted_destinations.clone())?;
            if steps.insert(step.from.version, step).is_some() {
                return Err(Error::invalid("duplicate migration source version"));
            }
        }
        for step in steps.values() {
            let (next, next_type) = if step.to.version == latest.version {
                (latest, TypeId::of::<L>())
            } else {
                let next = steps.get(&step.to.version).ok_or_else(|| {
                    Error::invalid(format!(
                        "missing migration from version {}",
                        step.to.version
                    ))
                })?;
                (&next.from, next.from_type)
            };
            next.check(step.to.clone())?;
            if next_type != step.to_type {
                return Err(Error::invalid(
                    "adjacent migrations must use the same Rust schema type",
                ));
            }
        }
        Ok(steps)
    }

    /// Opens the latest store, adopting every older shard through its converters.
    pub fn migrate(&self, layout: impl Into<Layout>) -> Result<(L, MigrationReport)> {
        let latest = L::default().schema_metadata();
        self.registry(&latest)?;
        let mut store = L::open_beside_older(layout)?;
        let (_, report) = self.refresh(&mut store)?;
        Ok((store, report))
    }

    /// Takes what peers have written since, in the latest version and in every older one.
    pub fn refresh(&self, store: &mut L) -> Result<(MergeReport, MigrationReport)> {
        let latest = L::default().schema_metadata();
        let registry = self.registry(&latest)?;
        let layout = store
            .layout()
            .cloned()
            .ok_or_else(|| Error::invalid("this store is not attached to a directory"))?;
        let mut merged = store.refresh_peers()?;
        let mut report = MigrationReport::default();
        for (version, first) in &registry {
            let Some((mut current, marks)) = (first.load)(&layout, store.shard_marks())? else {
                continue;
            };
            for (_, step) in registry.range(*version..) {
                let (next, applied) = (step.apply)(current)?;
                current = next;
                report.steps.push(applied);
            }
            let converted = current.downcast::<L>().map_err(|_| {
                Error::invalid("migration did not reach the latest Rust schema type")
            })?;
            let mut batches = Vec::new();
            for (table, held) in converted.tables().into_iter().enumerate() {
                batches.push(Batch {
                    table,
                    first: 0,
                    rows: held.export_rows()?,
                    mark: None,
                });
            }
            store.adopt_converted(batches, marks, converted.clock(), &mut merged)?;
        }
        merged.incompatible.retain(|path| {
            !registry.keys().any(|version| {
                path.to_string_lossy()
                    .ends_with(&format!(".v{version}.dbs"))
            })
        });
        Ok((merged, report))
    }
}

